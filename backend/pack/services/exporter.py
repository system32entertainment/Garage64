"""Export Garage64 database state into an OptiFine CEM resource pack."""

import json
from dataclasses import dataclass, field
from pathlib import Path

from django.conf import settings

from pack.models import CarVariant, EntityBody, ModelPart, VariantPart


@dataclass
class ExportResult:
    written: list[Path] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.errors


def export_all(pack_root: Path | str | None = None) -> ExportResult:
    """Write all JEM, JPM, and properties files from the database."""
    cem_dir = _cem_dir(pack_root)
    result = ExportResult()

    for part in ModelPart.objects.all():
        try:
            result.written.append(write_jpm(cem_dir, part))
        except Exception as exc:  # pragma: no cover - defensive aggregation path
            result.errors.append(f'{part.name}.jpm: {exc}')

    bodies: dict[int, list[CarVariant]] = {}
    for variant in CarVariant.objects.all().order_by('order'):
        try:
            result.written.extend(write_jem(cem_dir, variant))
        except Exception as exc:  # pragma: no cover - defensive aggregation path
            result.errors.append(f'{variant.file_name}.jem: {exc}')
        bodies.setdefault(variant.body_id, []).append(variant)

    for body_id, variants in bodies.items():
        body = EntityBody.objects.get(pk=body_id)
        try:
            result.written.extend(write_properties(cem_dir, body, variants))
        except Exception as exc:  # pragma: no cover - defensive aggregation path
            result.errors.append(f'{body.jem_file_name}.properties: {exc}')

    return result


def compiled_jem(variant: CarVariant) -> dict:
    """Return body data with variant parts inlined for the web viewer."""
    jem = json.loads(json.dumps(variant.body.body_data))
    if variant.texture_override:
        jem['texture'] = variant.texture_override

    attachments = []
    for vp in VariantPart.objects.filter(variant=variant).order_by('order'):
        entry = dict(vp.part.attachment_meta)
        entry['model'] = vp.part.jpm_path
        normalize_car_space_attachment(entry)
        entry.pop('model', None)

        jpm = json.loads(json.dumps(vp.part.part_data))
        normalize_known_part_data(vp.part.jpm_path, jpm)
        entry['submodels'] = [jpm]
        attachments.append(entry)

    if attachments:
        jem['models'] = [jem['models'][0]] + attachments + jem['models'][1:]

    return jem


def write_jem(cem_dir: Path, variant: CarVariant) -> list[Path]:
    """Build and write a .jem file for a CarVariant."""
    jem = json.loads(json.dumps(variant.body.body_data))
    if variant.texture_override:
        jem['texture'] = variant.texture_override

    attachments = []
    for vp in VariantPart.objects.filter(variant=variant).order_by('order'):
        entry = dict(vp.part.attachment_meta)
        entry['model'] = vp.part.jpm_path
        normalize_car_space_attachment(entry)
        attachments.append(entry)

    if attachments:
        jem['models'] = [jem['models'][0]] + attachments + jem['models'][1:]

    written = []
    out_path = cem_dir / f'{variant.file_name}.jem'
    _write_json(out_path, jem)
    written.append(out_path)

    for alias in cem_aliases(variant.file_name):
        alias_path = cem_dir / f'{alias}.jem'
        _write_json(alias_path, jem)
        written.append(alias_path)

    return written


def write_jpm(cem_dir: Path, part: ModelPart) -> Path:
    """Write a ModelPart's JPM file."""
    rel = part.jpm_path.split('optifine/cem/', 1)[-1]
    out_path = cem_dir / rel
    part_data = json.loads(json.dumps(part.part_data))
    normalize_known_part_data(part.jpm_path, part_data)
    _write_json(out_path, part_data)
    return out_path


def write_properties(cem_dir: Path, body: EntityBody, variants: list[CarVariant]) -> list[Path]:
    """Write the OptiFine .properties selector for triggered variants."""
    triggered = sorted([v for v in variants if v.trigger_name], key=lambda v: v.order)
    if not triggered:
        return []

    lines = ['# Auto-generated by Garage64 editor\n']
    for variant in triggered:
        lines.append(f'models.{variant.order}={variant.order + 1}\n')
        lines.append(f'name.{variant.order}={variant.trigger_name}\n')

    written = []
    props_path = cem_dir / f'{body.jem_file_name}.properties'
    props_path.parent.mkdir(parents=True, exist_ok=True)
    props_path.write_text(''.join(lines), encoding='utf-8')
    written.append(props_path)

    for alias in cem_aliases(body.jem_file_name):
        alias_path = cem_dir / f'{alias}.properties'
        alias_path.write_text(''.join(lines), encoding='utf-8')
        written.append(alias_path)

    return written


def cem_aliases(file_name: str) -> list[str]:
    """Keep legacy oak_boat names mirrored to active OptiFine boat names."""
    if file_name == 'oak_boat':
        return ['boat']
    if file_name.startswith('oak_boat') and file_name[len('oak_boat'):].isdigit():
        return [f'boat{file_name[len("oak_boat"):]}']
    return []


def normalize_car_space_attachment(entry: dict):
    """Known Miata JPM parts are authored in car space; avoid double front transforms."""
    model = entry.get('model', '')
    if model in {
        'minecraft:optifine/cem/miata/parts/miata_duce_wheels.jpm',
        'minecraft:optifine/cem/miata/parts/miata_popups.jpm',
    }:
        entry['part'] = 'front'
        entry['attach'] = True
        entry['translate'] = [0, -2, -5.5]
        entry['rotate'] = [0, -180, 0]
        entry['mirrorTexture'] = 'u'


def normalize_known_part_data(jpm_path: str, part_data: dict):
    """Keep known Garage64 JPM roots at their confirmed in-game placement."""
    if jpm_path != 'minecraft:optifine/cem/miata/parts/miata_duce_wheels.jpm':
        return
    for model in part_data.get('submodels', []):
        if model.get('id') == 'DuceKitWheels':
            model['translate'] = [0, 0, 11]


def _cem_dir(pack_root: Path | str | None) -> Path:
    root = Path(pack_root or settings.PACK_ROOT)
    return root / 'assets' / 'minecraft' / 'optifine' / 'cem'


def _write_json(path: Path, data: dict):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent='\t'), encoding='utf-8')
